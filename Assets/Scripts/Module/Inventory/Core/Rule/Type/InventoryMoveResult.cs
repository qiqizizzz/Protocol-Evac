namespace Module.Inventory.Core.Rule.Type
{
    public enum InventoryMoveResult
    {
        // ==================== 未初始化 ====================
        None = 0,

        // ==================== 成功与良性操作 ====================
        // 操作成功生效
        Success = 100,

        // 原地重复放置, 幂等放手, UI 静默且不重走表现
        SameSpot = 101,

        // ==================== 空间冲突 ====================
        // 目标区域超出网格边界
        OutOfBounds = 200,

        // 目标区域被其他物品占据
        Occupied = 201,

        // ==================== 业务规则限制 ====================
        // 物品配置不允许旋转
        NotRotatable = 300,

        // 目标容器超重
        WeightExceeded = 301,

        // ==================== 数据异常 ====================
        // 源容器中不存在该占位记录(幽灵引用)
        SourceNotFound = 400,

        // 物品归属权冲突, 实体已被其他容器持有
        OwnershipConflict = 401
    }
}